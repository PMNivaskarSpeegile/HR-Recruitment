-- 0025_bulk_import_batch.sql
-- Import batch tracking + audit for bulk candidate upload. Additive only:
-- a new table for each upload's metadata/counts/per-row report, and a nullable
-- FK on candidate_master pointing to the batch that CREATED the candidate
-- (NULL for manually-created or bulk-UPDATED candidates). Enables import
-- history, re-downloadable reports, and a safe (soft-delete) rollback.

SET search_path = ats, public;

CREATE TABLE IF NOT EXISTS bulk_import_batch (
    batch_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_uid       varchar(32),
    uploaded_by     integer,
    file_name       varchar(255),
    file_hash       varchar(64),
    source_id       smallint,
    requirement_id  integer,
    sheet_name      varchar(100),
    header_row      smallint,
    total_rows      integer NOT NULL DEFAULT 0,
    created_count   integer NOT NULL DEFAULT 0,
    updated_count   integer NOT NULL DEFAULT 0,
    duplicate_count integer NOT NULL DEFAULT 0,
    skipped_count   integer NOT NULL DEFAULT 0,
    status          varchar(12) NOT NULL DEFAULT 'PENDING',
    row_report      jsonb,
    error_message   text,
    created_on      timestamp NOT NULL DEFAULT now(),
    completed_on    timestamp,
    CONSTRAINT bulk_import_batch_uploaded_by_fk FOREIGN KEY (uploaded_by) REFERENCES user_master(user_id),
    CONSTRAINT bulk_import_batch_source_fk       FOREIGN KEY (source_id)   REFERENCES source_master(source_id),
    CONSTRAINT bulk_import_batch_requirement_fk  FOREIGN KEY (requirement_id) REFERENCES requirement_tracker(req_id)
);

CREATE INDEX IF NOT EXISTS ix_bulk_import_batch_uploaded_by ON bulk_import_batch (uploaded_by);

ALTER TABLE candidate_master
    ADD COLUMN IF NOT EXISTS import_batch_id integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE table_schema = 'ats' AND constraint_name = 'candidate_master_import_batch_fk'
    ) THEN
        ALTER TABLE candidate_master
            ADD CONSTRAINT candidate_master_import_batch_fk
            FOREIGN KEY (import_batch_id) REFERENCES bulk_import_batch(batch_id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_candidate_master_import_batch ON candidate_master (import_batch_id);
